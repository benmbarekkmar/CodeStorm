def rewrite(path, lang):
    text = open(path, encoding='utf-8').read()
    blocks = parse_blocks(text)
    out = []
    filled = 0
    kept = 0
    untranslated = 0
    for refs, id_inner, str_inner, fuzzy, is_header in blocks:
        if is_header:
            out.append('\n'.join(refs + ['msgid ""', 'msgstr "%s"' % str_inner]))
            continue
        key = unescape(id_inner)
        pair = TR.get(key)
        if pair:
            val = escape(pair[0] if lang == 'fr' else pair[1])
            out.append('\n'.join(refs + ['msgid "%s"' % id_inner, 'msgstr "%s"' % val]))
            filled += 1
        elif str_inner and not fuzzy:
            # preserve existing good translation
            out.append('\n'.join(refs + ['msgid "%s"' % id_inner, 'msgstr "%s"' % str_inner]))
            kept += 1
        else:
            out.append('\n'.join(refs + ['msgid "%s"' % id_inner, 'msgstr ""']))
            untranslated += 1
    open(path, 'w', encoding='utf-8').write('\n\n'.join(out) + '\n')
    print(lang, 'dict=%d kept=%d untranslated=%d' % (filled, kept, untranslated))


