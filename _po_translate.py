def parse_blocks(text):
    # returns list of (comment_block, msgid_raw_inner, msgstr_raw_inner, is_fuzzy, is_header)
    blocks = re.split(r'\n[ \t]*\n', text)
    out = []
    for b in blocks:
        lines = b.split('\n')
        refs = [l for l in lines if l.strip().startswith('#') and l.strip() != '#, fuzzy']
        fuzzy = any(l.strip() == '#, fuzzy' for l in lines)
        # gather msgid segments
        field = None
        msgid_segs = []
        msgstr_segs = []
        for l in lines:
            if l.startswith('msgid '):
                field = 'id'
                msgid_segs += re.findall(r'"((?:[^"\\]|\\.)*)"', l)
            elif l.startswith('msgstr'):
                field = 'str'
                msgstr_segs += re.findall(r'"((?:[^"\\]|\\.)*)"', l)
            elif l.startswith('"'):
                segs = re.findall(r'"((?:[^"\\]|\\.)*)"', l)
                if field == 'id':
                    msgid_segs += segs
                elif field == 'str':
                    msgstr_segs += segs
        has_msgid = any(l.startswith('msgid ') for l in lines)
        if not has_msgid:
            continue
        id_inner = ''.join(msgid_segs)
        str_inner = ''.join(msgstr_segs)
        is_header = (id_inner == '')
        out.append((refs, id_inner, str_inner, fuzzy, is_header))
    return out


def unescape(s):
    return s.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')


def escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


